import { expect, test } from '@playwright/test'

test('offers signup and login on the public site', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Know what’s in every box/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Free', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Family', exact: true })).toBeVisible()
  await expect(page.getByText('€29', { exact: false })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Get started free' }).click()
  await expect(page.getByRole('heading', { name: 'Create your account' })).toBeVisible()
  await page.getByRole('link', { name: /Already have an account/ }).click()
  await expect(page.getByRole('heading', { name: 'Log in' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue with Google' })).toBeVisible()
})

test('follows the device theme until a choice is saved', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('link', { name: 'Log in', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Switch to light mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})

test('lets signed-out visitors search sample boxes and open a QR label', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Try the demo' }).click()
  await page.getByRole('button', { name: 'Try “spare batteries”' }).click()
  await expect(page.getByRole('status')).toHaveText('1 box found')
  await page.getByRole('link', { name: /Small fixes & tools/ }).click()
  await expect(page).toHaveURL('/demo/tools')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Small fixes & tools' })).toBeVisible()
  await expect(page.getByText('Spare batteries', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Show sample QR label' }).click()
  const dialog = page.getByRole('dialog', { name: 'QR label for Small fixes & tools' })
  await expect(dialog.getByRole('img')).toHaveAttribute('src', /^data:image\/png;base64,/)
  await dialog.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('link', { name: 'Create your own inventory for free' }).click()
  await expect(page.getByRole('heading', { name: 'Create your account' })).toBeVisible()
})
