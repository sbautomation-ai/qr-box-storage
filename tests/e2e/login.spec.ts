import { expect, test } from '@playwright/test'

test('offers signup and login on the public site', async ({ page }) => {
  await page.goto('/')
  await expect(page.getByRole('heading', { name: /Know what’s in every box/ })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Free', exact: true })).toBeVisible()
  await expect(page.getByRole('heading', { name: 'Family', exact: true })).toBeVisible()
  await expect(page.getByText('€29', { exact: false })).toBeVisible()
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  await page.getByRole('link', { name: 'Get started free' }).click()
  await expect(page.getByRole('heading', { name: 'Create your account' })).toBeVisible()
  await page.getByRole('link', { name: /Already have an account/ }).click()
  await expect(page.getByRole('heading', { name: 'Log in' })).toBeVisible()
  await expect(page.getByRole('button', { name: 'Continue with Google' })).toBeVisible()
})

test('follows the device theme until a choice is saved', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.emulateMedia({ colorScheme: 'light' })
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
  await page.getByRole('button', { name: 'Switch to dark mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('link', { name: 'Log in', exact: true }).click()
  await page.reload()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('button', { name: 'Switch to light mode' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'light')
})

test('lets signed-out visitors search and open sample boxes in the homepage demo', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Try the demo' }).first().press('Enter')
  await expect(page).toHaveURL('/#try-demo')
  const demo = page.getByRole('region', { name: 'Sample inventory' })
  await expect(demo).toBeFocused()
  await expect(demo.getByRole('listitem')).toHaveCount(3)

  const search = demo.getByRole('searchbox', { name: 'Search sample inventory' })
  await search.fill('garage')
  await expect(demo.getByRole('status')).toHaveText('2 boxes found')
  await search.fill('camping')
  await expect(demo.getByRole('status')).toHaveText('1 box found')
  await expect(demo.getByRole('button', { name: /Camping kit/ })).toBeVisible()
  await search.fill('no matching box')
  await expect(demo.getByRole('status')).toHaveText('No boxes match. Try another item, box or location.')
  await search.fill('extension cord')
  const result = demo.getByRole('button', { name: /Small fixes & tools/ })
  await result.press('Enter')
  await expect(demo.getByRole('heading', { name: 'Small fixes & tools' })).toBeFocused()
  await expect(demo.getByText('Garage · Left shelf')).toBeVisible()
  await expect(demo.getByRole('listitem').filter({ hasText: 'Extension cord' })).toContainText('× 2')
  await expect(page).toHaveURL('/#try-demo')

  const qrButton = demo.getByRole('button', { name: 'Show sample QR label' })
  await qrButton.press('Enter')
  const dialog = page.getByRole('dialog', { name: 'QR label for Small fixes & tools' })
  await expect(dialog.getByRole('img')).toHaveAttribute('src', /^data:image\/png;base64,/)
  await expect(dialog.getByRole('button', { name: 'Close dialog' })).toBeFocused()
  await page.keyboard.press('Tab')
  await expect(dialog.getByRole('link', { name: 'Open sample box' })).toBeFocused()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeHidden()
  await expect(qrButton).toBeFocused()

  await demo.getByRole('button', { name: 'Back to sample boxes' }).click()
  await expect(search).toHaveValue('extension cord')
  await expect(result).toBeFocused()
})

test('opens the dark homepage demo from pricing and follows its same-device link', async ({ page }) => {
  await page.emulateMedia({ colorScheme: 'dark' })
  await page.goto('/#pricing')
  await expect(page.locator('html')).toHaveAttribute('data-theme', 'dark')
  await page.getByRole('region', { name: 'Plans for your household' }).getByRole('link', { name: 'Try the demo' }).click()
  await expect(page).toHaveURL('/#try-demo')
  const demo = page.getByRole('region', { name: 'Sample inventory' })
  await expect(demo.getByRole('heading', { name: 'Sample inventory' })).toBeInViewport()
  await demo.getByRole('button', { name: 'Try “spare batteries”' }).click()
  await expect(demo.getByRole('searchbox')).toHaveValue('spare batteries')
  await demo.getByRole('button', { name: /Small fixes & tools/ }).click()
  await demo.getByRole('button', { name: 'Show sample QR label' }).click()
  await page.getByRole('dialog').getByRole('link', { name: 'Open sample box' }).click()
  await expect(page).toHaveURL('/demo/tools')
  await expect(page.getByRole('heading', { name: 'Small fixes & tools' })).toBeVisible()
})

test('lets signed-out visitors reach the full demo and open a shareable sample box', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('link', { name: 'Open full demo' }).click()
  await expect(page).toHaveURL('/demo')
  await page.getByRole('button', { name: 'Try “spare batteries”' }).click()
  await expect(page.getByRole('status')).toHaveText('1 box found')
  await page.getByRole('link', { name: /Small fixes & tools/ }).click()
  await expect(page).toHaveURL('/demo/tools')
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Small fixes & tools' })).toBeVisible()
  await expect(page.getByText('Spare batteries', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Show sample QR label' }).click()
  const dialog = page.getByRole('dialog', { name: 'QR label for Small fixes & tools' })
  await expect(dialog.getByRole('img')).toHaveAttribute('src', /^data:image\/png;base64,/)
  await dialog.getByRole('button', { name: 'Close' }).click()
  await page.getByRole('link', { name: 'Create your own inventory for free' }).click()
  await expect(page.getByRole('heading', { name: 'Create your account' })).toBeVisible()
})
